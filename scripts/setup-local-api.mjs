// Generate the PostgREST configuration and Supabase-compatible API keys for a
// local machine, so the backend can run without Docker or the Supabase CLI.
//
//   node scripts/setup-local-api.mjs --database 'postgresql://postgres:PW@127.0.0.1:5432/trez_local'
//
//   --out <dir>      where to write postgrest.conf   (default local/)
//   --port <n>       PostgREST port                  (default 3000)
//   --gateway <n>    gateway port                    (default 8000)
//   --print-env      print env lines instead of writing files
//
// The anon and service_role keys are HS256 JWTs signed with a generated
// jwt-secret, which is exactly how Supabase issues them: PostgREST validates
// the signature and adopts the role named in the payload.
//
// This does not download or run PostgREST. Install it yourself and point
// POSTGREST_PATH at it, or put it on PATH.

import { createHmac, randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const args = {
    database: '',
    out: path.join(repoRoot, 'local'),
    port: '3000',
    gateway: '8000',
    printEnv: false,
    force: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    const value = argv[index + 1];
    if (flag === '--database') { args.database = value; index += 1; }
    else if (flag === '--out') { args.out = path.resolve(value); index += 1; }
    else if (flag === '--port') { args.port = value; index += 1; }
    else if (flag === '--gateway') { args.gateway = value; index += 1; }
    else if (flag === '--print-env') { args.printEnv = true; }
    else if (flag === '--force') { args.force = true; }
    else if (flag === '-h' || flag === '--help') { args.help = true; }
    else throw new Error(`Unknown argument: ${flag}`);
  }

  return args;
}

function base64url(input) {
  return Buffer.from(input).toString('base64url');
}

export function signJwt(payload, secret) {
  const header = base64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
  const body = base64url(JSON.stringify(payload));
  const signature = createHmac('sha256', secret).update(`${header}.${body}`).digest('base64url');
  return `${header}.${body}.${signature}`;
}

export function buildApiKeys(secret, { issuer = 'trez-local', years = 10 } = {}) {
  const issuedAt = Math.floor(Date.now() / 1000);
  const expiresAt = issuedAt + years * 365 * 24 * 60 * 60;
  const claims = (role) => ({ iss: issuer, role, iat: issuedAt, exp: expiresAt });

  return {
    anonKey: signJwt(claims('anon'), secret),
    serviceRoleKey: signJwt(claims('service_role'), secret),
  };
}

export function buildPostgrestConfig({ databaseUrl, port, jwtSecret }) {
  return [
    '# Generated by scripts/setup-local-api.mjs. Contains secrets; do not commit.',
    `db-uri = "${databaseUrl}"`,
    '',
    '# auth is exposed because the local Hub auth provider owns auth.users.',
    'db-schemas = "public,auth"',
    '',
    '# Unauthenticated requests act as anon. The backend always presents the',
    '# service_role key, so it is never limited by this.',
    'db-anon-role = "anon"',
    '',
    `jwt-secret = "${jwtSecret}"`,
    'jwt-secret-is-base64 = false',
    '',
    'server-host = "127.0.0.1"',
    `server-port = ${port}`,
    '',
    'db-pool = 10',
    '',
  ].join('\n');
}

// Importing this module must not run the generator; the tests import the
// helpers above.
const isDirectRun =
  process.argv[1] &&
  import.meta.url === new URL(`file://${process.argv[1]}`).href.replace(/\\/g, '/');

if (isDirectRun) {
const args = parseArgs(process.argv.slice(2));

if (args.help) {
  process.stdout.write(
    'Usage: node scripts/setup-local-api.mjs --database <postgres url> [--out dir] [--port n] [--gateway n] [--print-env]\n',
  );
  process.exit(0);
}

if (!args.database) {
  process.stderr.write('A --database connection string is required.\n');
  process.exit(2);
}

if (!/^postgres(ql)?:\/\//.test(args.database)) {
  process.stderr.write('The --database value must be a postgres:// or postgresql:// URL.\n');
  process.exit(2);
}

// Refuse a non-local database. This wires up a development gateway whose keys
// are written to disk in plain text; pointing it at a shared host would expose
// that database through it.
const host = new URL(args.database).hostname.toLowerCase();
if (!['localhost', '127.0.0.1', '::1', '[::1]'].includes(host)) {
  process.stderr.write('The --database host must be localhost or 127.0.0.1.\n');
  process.exit(2);
}

const jwtSecret = randomBytes(32).toString('base64url');
const { anonKey, serviceRoleKey } = buildApiKeys(jwtSecret);
const localAuthSecret = randomBytes(32).toString('base64url');
const gatewayUrl = `http://127.0.0.1:${args.gateway}`;

const backendEnv = [
  '# Generated for a Docker-free local stack. Do not commit.',
  `SUPABASE_URL=${gatewayUrl}`,
  `SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  'HUB_AUTH_MODE=local',
  `HUB_LOCAL_AUTH_SECRET=${localAuthSecret}`,
  'HUB_PUBLIC_BACKEND_URL=http://localhost:8080',
  'HUB_COOKIE_SECURE=0',
  'PORT=8080',
  'HOST=127.0.0.1',
  'CLIENT_URL=http://localhost:5173',
  '',
].join('\n');

const frontendEnv = [
  '# Generated for a Docker-free local stack. Do not commit.',
  'VITE_API_URL=http://localhost:8080',
  'VITE_TREZ_HUB_ENABLED=true',
  '',
].join('\n');

const config = buildPostgrestConfig({
  databaseUrl: args.database,
  port: args.port,
  jwtSecret,
});

if (args.printEnv) {
  process.stdout.write(`${backendEnv}\n`);
  process.exit(0);
}

// These files usually already hold a working configuration. Overwriting one
// silently would strand a machine with no way back, so require --force.
const backendEnvPath = path.join(repoRoot, 'backend', '.env.local');
const frontendEnvPath = path.join(repoRoot, 'frontend', '.env.local');
const existing = [backendEnvPath, frontendEnvPath].filter((file) => existsSync(file));

if (existing.length > 0 && !args.force) {
  process.stderr.write(
    `Refusing to overwrite:\n${existing.map((file) => `  ${file}`).join('\n')}\n` +
      'Back them up and re-run with --force, or use --print-env to see the values.\n',
  );
  process.exit(2);
}

await mkdir(args.out, { recursive: true });
const configPath = path.join(args.out, 'postgrest.conf');
await writeFile(configPath, config, { mode: 0o600 });
await writeFile(backendEnvPath, backendEnv, { mode: 0o600 });
await writeFile(frontendEnvPath, frontendEnv, { mode: 0o600 });

process.stdout.write(
  [
    `Wrote ${configPath}`,
    'Wrote backend/.env.local and frontend/.env.local',
    '',
    'Start the stack in three terminals:',
    `  1. postgrest ${configPath}`,
    `  2. LOCAL_API_GATEWAY_PORT=${args.gateway} POSTGREST_URL=http://127.0.0.1:${args.port} node scripts/local-api-gateway.mjs`,
    '  3. npm run dev:backend   (and npm run dev:frontend)',
    '',
    'PostgREST is not installed by this script. Install it and put it on PATH.',
    '',
  ].join('\n'),
);
}
